_CN = "零一二三四五六七八九"


def _qian_to_str(qian: int) -> str:
    """钱数 → 「X两Y钱」字符串（10 钱 = 1 两，中文数字，传统写法）。"""
    liang, q = divmod(qian, 10)
    if liang == 0:
        return f"{_CN[q]}钱"
    if q == 0:
        return f"{_CN[liang]}两"
    return f"{_CN[liang]}两{_CN[q]}钱"


@dataclass
class ChengGuResult:
    """称骨结果。"""
    year_gz: str            # 年柱干支
    lunar_month: int        # 农历月
    lunar_day: int          # 农历日
    hour_zhi: str           # 时支
    year_qian: int          # 年骨重（钱）
    month_qian: int
    day_qian: int
    hour_qian: int
    total_qian: int         # 总骨重（钱）
    verdict: str | None     # 判词（超出表范围时 None）
    caliber: str = ""       # 时辰口径声明（出生信息推算时填写）

    @property
    def total_str(self) -> str:
        return _qian_to_str(self.total_qian)

    def breakdown(self) -> list[tuple[str, str]]:
        return [
            (f"年（{self.year_gz}）", _qian_to_str(self.year_qian)),
            (f"月（农历{self.lunar_month}月）", _qian_to_str(self.month_qian)),
            (f"日（农历{self.lunar_day}）", _qian_to_str(self.day_qian)),
            (f"时（{self.hour_zhi}时）", _qian_to_str(self.hour_qian)),
        ]

    def __str__(self) -> str:  # pragma: no cover - 展示用
        lines = [f"称骨（{self.year_gz}年 农历{self.lunar_month}月{self.lunar_day}日 {self.hour_zhi}时）"]
        lines += [f"  {k} = {v}" for k, v in self.breakdown()]
        lines.append(f"  总骨重 = {self.total_str}")
        if self.verdict:
            lines.append(f"  判词：{self.verdict}")
        else:
            lines.append("  判词：超出通行表范围（无记录）")
        if self.caliber:
            lines.append(f"  {self.caliber}")
        return "\n".join(lines)


def calc(year_gz: str, lunar_month: int, lunar_day: int, hour_zhi: str) -> ChengGuResult:
    """计算称骨。

    :param year_gz: 农历年干支（如「甲子」），按正月初一换年（通行口径）。
    :param lunar_month: 农历月 1-12。
    :param lunar_day: 农历日 1-30。
    :param hour_zhi: 时支（子丑寅卯辰巳午未申酉戌亥）。
    """
    assert year_gz in YEAR_WEIGHT, f"非法年柱：{year_gz}"
    assert 1 <= lunar_month <= 12
    assert 1 <= lunar_day <= 30
    assert hour_zhi in "子丑寅卯辰巳午未申酉戌亥"
    yq = YEAR_WEIGHT[year_gz]
    mq = MONTH_WEIGHT[lunar_month - 1]
    dq = DAY_WEIGHT[lunar_day - 1]
    hq = HOUR_WEIGHT["子丑寅卯辰巳午未申酉戌亥".index(hour_zhi)]
    total = yq + mq + dq + hq
    return ChengGuResult(
        year_gz=year_gz, lunar_month=lunar_month, lunar_day=lunar_day, hour_zhi=hour_zhi,
        year_qian=yq, month_qian=mq, day_qian=dq, hour_qian=hq,
        total_qian=total, verdict=VERDICT.get(total),
    )


def calc_from_birth(birth: "BirthInfo", nb: "NormalizedBirth") -> ChengGuResult:
    """出生信息计算称骨（农历正月初一换年，时辰按校正后钟点），并标注口径。"""
    res = calc(nb.lunar_year_ganzhi, abs(nb.lunar_month), nb.lunar_day, nb.time_zhi)
    if nb.true_solar_shift_min is not None:
        res.caliber = (f"时辰口径：真太阳时支（校正 {nb.true_solar_shift_min:+.1f} 分，"
                       "与八字/紫微一致）")
    else:
        res.caliber = "时辰口径：钟表时支（未做真太阳时校正）"
    return res
